import { eq, like, count } from 'drizzle-orm';
import { db } from '../src/db/index.ts';
import {
  users,
  categories,
  subcategories,
  faqs,
  forumTopics,
  forumPosts,
  feedbacks,
  privateMessages
} from '../src/db/schema.ts';

export interface ProductionSnapshot {
  usersCount: number;
  categoriesCount: number;
  subcategoriesCount: number;
  faqsCount: number;
  topicsCount: number;
  postsCount: number;
  feedbacksCount: number;
  pmsCount: number;
}

export class TestGuardian {
  public readonly runId: string;
  public readonly prefix: string;
  private isTornDown: boolean = false;
  private initialSnapshot: ProductionSnapshot | null = null;
  private boundSignals: Array<() => void> = [];

  constructor() {
    this.runId = `tst_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`;
    this.prefix = `${this.runId}_`;
  }

  /**
   * Initializes the test guardian:
   * 1. Traps process interruption signals (SIGINT, SIGTERM, SIGHUP, uncaughtException)
   * 2. Cleans up any orphaned test artifacts from previous ungraceful exits
   * 3. Captures an immutable snapshot of production data
   */
  async setup(): Promise<void> {
    this.registerSignalTraps();

    // Clean any stale mock data left behind by previous aborted runs
    await this.purgeAllMockArtifacts('tst_');

    // Capture initial production data snapshot
    this.initialSnapshot = await this.captureProductionSnapshot();
    console.log(`[TestGuardian] Initialized test session: ${this.runId}`);
    console.log(`[TestGuardian] Production baseline snapshot:`, this.initialSnapshot);
  }

  /**
   * Captures the record counts of non-test (production) data
   */
  async captureProductionSnapshot(): Promise<ProductionSnapshot> {
    const [u] = await db.select({ val: count() }).from(users);
    const [c] = await db.select({ val: count() }).from(categories);
    const [s] = await db.select({ val: count() }).from(subcategories);
    const [f] = await db.select({ val: count() }).from(faqs);
    const [t] = await db.select({ val: count() }).from(forumTopics);
    const [p] = await db.select({ val: count() }).from(forumPosts);
    const [fb] = await db.select({ val: count() }).from(feedbacks);
    const [pm] = await db.select({ val: count() }).from(privateMessages);

    return {
      usersCount: Number(u?.val || 0),
      categoriesCount: Number(c?.val || 0),
      subcategoriesCount: Number(s?.val || 0),
      faqsCount: Number(f?.val || 0),
      topicsCount: Number(t?.val || 0),
      postsCount: Number(p?.val || 0),
      feedbacksCount: Number(fb?.val || 0),
      pmsCount: Number(pm?.val || 0),
    };
  }

  /**
   * Purges all mock artifacts generated by this test session or matching a prefix
   */
  async teardown(): Promise<void> {
    if (this.isTornDown) return;
    this.isTornDown = true;

    console.log(`[TestGuardian] Running teardown for session: ${this.runId}...`);
    await this.purgeAllMockArtifacts(this.prefix);
    this.removeSignalTraps();
    console.log(`[TestGuardian] Teardown complete. All session mock artifacts purged.`);
  }

  /**
   * Verifies that production data was completely untouched throughout the test
   */
  async verifyProductionIntegrity(): Promise<boolean> {
    if (!this.initialSnapshot) {
      throw new Error('Initial baseline snapshot was never captured.');
    }

    const currentSnapshot = await this.captureProductionSnapshot();
    const matches =
      currentSnapshot.usersCount === this.initialSnapshot.usersCount &&
      currentSnapshot.categoriesCount === this.initialSnapshot.categoriesCount &&
      currentSnapshot.subcategoriesCount === this.initialSnapshot.subcategoriesCount &&
      currentSnapshot.faqsCount === this.initialSnapshot.faqsCount &&
      currentSnapshot.topicsCount === this.initialSnapshot.topicsCount &&
      currentSnapshot.postsCount === this.initialSnapshot.postsCount &&
      currentSnapshot.feedbacksCount === this.initialSnapshot.feedbacksCount &&
      currentSnapshot.pmsCount === this.initialSnapshot.pmsCount;

    if (!matches) {
      console.error('[TestGuardian] INTEGRITY VIOLATION DETECTED!');
      console.error('Expected baseline:', this.initialSnapshot);
      console.error('Current state:', currentSnapshot);
      return false;
    }

    console.log(`[TestGuardian] ✓ Production data integrity verified: 100% untouched.`);
    return true;
  }

  /**
   * Emergency signal handler to ensure mock data teardown happens even when Ctrl+C or kill is received
   */
  private registerSignalTraps(): void {
    const handleAbort = async (signalName: string) => {
      console.warn(`\n[TestGuardian] Caught interruption signal: ${signalName}. Executing emergency mock data purge...`);
      try {
        await this.purgeAllMockArtifacts(this.prefix);
        console.warn(`[TestGuardian] Emergency teardown successfully completed.`);
      } catch (err) {
        console.error(`[TestGuardian] Emergency teardown encountered an error:`, err);
      }
      process.exit(1);
    };

    const sigintHandler = () => handleAbort('SIGINT');
    const sigtermHandler = () => handleAbort('SIGTERM');
    const sighupHandler = () => handleAbort('SIGHUP');

    process.on('SIGINT', sigintHandler);
    process.on('SIGTERM', sigtermHandler);
    process.on('SIGHUP', sighupHandler);

    this.boundSignals.push(
      () => process.off('SIGINT', sigintHandler),
      () => process.off('SIGTERM', sigtermHandler),
      () => process.off('SIGHUP', sighupHandler)
    );
  }

  private removeSignalTraps(): void {
    for (const unbind of this.boundSignals) {
      unbind();
    }
    this.boundSignals = [];
  }

  /**
   * Internal database cleaner targeting only mock rows matching the prefix
   */
  private async purgeAllMockArtifacts(targetPrefix: string): Promise<void> {
    try {
      const match = `${targetPrefix}%`;

      // 1. Delete mock forum posts
      await db.delete(forumPosts).where(like(forumPosts.id, match));
      await db.delete(forumPosts).where(like(forumPosts.topicId, match));
      await db.delete(forumPosts).where(like(forumPosts.author, match));

      // 2. Delete mock forum topics
      await db.delete(forumTopics).where(like(forumTopics.id, match));
      await db.delete(forumTopics).where(like(forumTopics.author, match));

      // 3. Delete mock FAQs
      await db.delete(faqs).where(like(faqs.id, match));

      // 4. Delete mock subcategories & categories
      await db.delete(subcategories).where(like(subcategories.id, match));
      await db.delete(categories).where(like(categories.id, match));

      // 5. Delete mock private messages
      await db.delete(privateMessages).where(like(privateMessages.id, match));
      await db.delete(privateMessages).where(like(privateMessages.fromUser, match));
      await db.delete(privateMessages).where(like(privateMessages.toUser, match));

      // 6. Delete mock feedbacks
      await db.delete(feedbacks).where(like(feedbacks.id, match));

      // 7. Delete mock users
      await db.delete(users).where(like(users.username, match));
      await db.delete(users).where(like(users.uid, match));
    } catch (err) {
      console.warn(`[TestGuardian] Warning during mock purge with prefix "${targetPrefix}":`, err);
    }
  }
}
